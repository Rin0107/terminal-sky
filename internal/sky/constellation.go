// Segment は星座線 1 本。両端の星の高度・方位 (地平線より下のこともある)。
type Segment struct{ A, B Seen }

// Figure は 1 つの星座の、今見えている線と星。
type Figure struct {
	Name     string
	Segments []Segment // 両端の少なくとも一方が地平線より上の線
	Stars    []Seen    // 線が通る星のうち地平線より上のもの (重ねない・線の順)
}

// segmentShown は線を描くか。両端とも地平線より下なら描かない。
// 仕様: spec/sky.smt2 の 4。
func segmentShown(a, b Seen) bool { return a.Alt > 0 || b.Alt > 0 }

// Figures は、地平線より上に線が 1 本でもある星座を返す。table にない名前の線は飛ばす。
func Figures(cons []Constellation, table []Star, c City, t time.Time) []Figure {
	idx := make(map[string]Star, len(table))
	for _, s := range table {
		idx[s.Name] = s
	}
	where := func(s Star) Seen {
		alt, az := Horizontal(s, c, t)
		return Seen{Star: s, Alt: alt, Az: az}
	}
	var out []Figure
	for _, con := range cons {
		f := Figure{Name: con.Name}
		added := map[string]bool{}
		for _, l := range con.Lines {
			sa, okA := idx[l[0]]
			sb, okB := idx[l[1]]
			if !okA || !okB {
				continue
			}
			a, b := where(sa), where(sb)
			if !segmentShown(a, b) {
				continue
			}
			f.Segments = append(f.Segments, Segment{A: a, B: b})
			for _, s := range []Seen{a, b} {
				if s.Alt > 0 && !added[s.Star.Name] {
					added[s.Star.Name] = true
					f.Stars = append(f.Stars, s)
				}
			}
		}
		if len(f.Segments) > 0 {
			out = append(out, f)
		}
	}
	return out
}
