package sky

// Star は目録の 1 つの恒星。座標は J2000.0 の赤経 (時)・赤緯 (度)。
type Star struct {
	Name string  // 日本語の名前 (表示に使う)
	RA   float64 // 赤経 [時] (J2000.0)
	Dec  float64 // 赤緯 [度] (J2000.0)
	Mag  float64 // 実視等級
}

// hms は 時・分・秒 を時に直す。
func hms(h, m, s float64) float64 { return h + m/60 + s/3600 }

// dms は 度・分・秒 を度に直す。符号は度の符号に従う (0 度台の負の値は目録にない)。
func dms(d, m, s float64) float64 {
	if d < 0 {
		return d - m/60 - s/3600
	}
	return d + m/60 + s/3600
}

